"""Synthetic robot motion -> raw MPU-6050 samples, with known truth. For tests and `imu_viz.py --demo`.

Given a body attitude trajectory R_wb(t) (world <- body, z up), the raw sensor output is generated by inverting the
calibration: specific force at the sensor = R_wb^T (g e_z) + alpha x r + w x (w x r) (stationary body), then the
sensor-frame rotation, the accel scale/offset and the gyro bias.
"""
import json

import numpy as np

G0 = 9.80665


def rot_exp(w):
    """Rotation matrix for rotation vector w (Rodrigues)."""
    th = np.linalg.norm(w)
    if th < 1e-12:
        return np.eye(3)
    k = w / th
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return np.eye(3) + np.sin(th) * K + (1 - np.cos(th)) * K @ K


def rot_log(M):
    c = np.clip((np.trace(M) - 1) / 2, -1, 1)
    th = np.arccos(c)
    v = np.array([M[2, 1] - M[1, 2], M[0, 2] - M[2, 0], M[1, 0] - M[0, 1]])
    return v / 2 if th < 1e-8 else v * th / (2 * np.sin(th))


def euler(yaw, pitch, roll):  # R_wb = Rz(yaw) Ry(pitch) Rx(roll)
    cz, sz, cy, sy, cx, sx = np.cos(yaw), np.sin(yaw), np.cos(pitch), np.sin(pitch), np.cos(roll), np.sin(roll)
    Rz = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]])
    Ry = np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]])
    Rx = np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])
    return Rz @ Ry @ Rx


def trajectory(T=60.0, rate=50.0):
    """Hand-like motion: still, nose-up/down rocks, left/right rocks, then a yaw spin both ways."""
    t = np.arange(0, T, 1.0 / rate)
    env =lambda a, b: np.clip(np.minimum(t - a, b - t) / 1.0, 0, 1)  # smooth on/off window [a, b]  # noqa: E731
    pitch = -np.radians(28) * np.sin(2 * np.pi * 0.2 * (t - 4)) * env(4, 14)  # pitch about +y: negative = nose up
    roll = np.radians(22) * np.sin(2 * np.pi * 0.2 * (t - 16)) * env(16, 26)
    yaw = np.radians(120) * np.sin(2 * np.pi * 0.12 * (t - 28)) * env(28, 44)
    Rwb = np.array([euler(y, p, r) for y, p, r in zip(yaw, pitch, roll)])
    return t, Rwb


def raw_from_truth(calib_path, t, Rwb, r=None, noise=0.0, seed=0):
    c = json.load(open(calib_path))
    R = np.array(c["R_body_from_sensor"]); off, sc = np.array(c["acc_offset"]), np.array(c["acc_scale"])
    bias = np.array(c["gyro_bias_sensor"])
    r = np.array(c.get("lever_arm_body_m", [0, 0, 0])) if r is None else np.array(r)
    dt = np.diff(t, prepend=t[0] - (t[1] - t[0]))
    w_b = np.array([rot_log(Rwb[k - 1].T @ Rwb[k]) / dt[k] if k else np.zeros(3) for k in range(len(t))])
    alpha = np.gradient(w_b, t, axis=0)
    a_origin = np.array([Rk.T @ np.array([0, 0, G0]) for Rk in Rwb])
    a_sens_b = a_origin + np.cross(alpha, r) + np.cross(w_b, np.cross(w_b, r))
    rng = np.random.RandomState(seed)
    a_raw = (a_sens_b @ R) / sc + off + noise * rng.randn(len(t), 3)  # (v_body^T R) = (R^T v_body)^T
    w_raw = w_b @ R + bias + noise * 0.1 * rng.randn(len(t), 3)
    return dict(t=t, a_raw=a_raw, w_raw=w_raw, w_b=w_b, a_origin=a_origin,
                g_true=-np.array([Rk.T @ np.array([0, 0, 1.0]) for Rk in Rwb]))
